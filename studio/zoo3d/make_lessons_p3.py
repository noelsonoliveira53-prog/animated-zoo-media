def Q(t, pause=3.2): return {"t": t, "pause": pause}
def q0(t): return {"t": t, "pause": 0.4}
def X(t, shot): return [t, shot]
def ex(prop, at, on, off=None, **kw):
    d = {"prop": prop, "at": at, "on": on}
    if off is not None: d["off"] = off
    for k in ("times", "leave", "keep"):
        if k in kw: d[k] = kw.pop(k)
    if kw: d["opts"] = kw
    return d
def chk(line, a, b, right, colors=None, hold=2.0):
    """Question round on `line`, answered on the next line: two signs + thinking dots, confetti on the right one."""
    d = {"a": a, "b": b, "right": right, "ask": [line], "answer": [line + 1], "hold": hold}
    if colors: d["colors"] = colors
    return d
def yn(right, line=1, hold=2.4): return chk(line, "YES", "NO", right, YN, hold)
def one23(line, at, n=3, dx=0.75, s=1.0, off=None):
    words = ["one", "two", "three", "four", "five", "six", "seven"][:n]
    return ex("count", at, [line, "one"], off, n=n, dx=dx, s=s, times=[[line, w] for w in words])
def clues(reveal=4):
    """Mystery box + three numbered clue badges + thinking dots (lines 0-3), gone at the reveal line."""
    return [ex("qbox", "mid", [0], [reveal])] + [ex("badge", list(BX[k]), [k + 1], [reveal], text=str(k + 1), s=1.1, color=("#ffb627", "#3db8ff", "#3cc45a")[k]) for k in range(3)] + \
           [ex("dots", "dots", [3, "end"], [reveal])]


