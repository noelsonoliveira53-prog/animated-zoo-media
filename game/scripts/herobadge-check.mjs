// Hero badge: partway XP (alive), then a downed hero mid-respawn, then a level-up flare; crops of the badge corner.
import { createRequire } from 'node:module';
import { preview } from 'vite';
const require = createRequire(import.meta.url);
const pw = require('playwright');
const name = process.argv[2] ?? 'herobadge';
const server = await preview({ preview: { port: 4340, strictPort: true } });
const browser = await pw.chromium.launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 720 }, deviceScaleFactor: 2 });
const errors = [];
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
page.on('pageerror', (e) => errors.push(String(e)));
await page.goto('http://localhost:4340/');
await page.waitForTimeout(900);
await page.evaluate(() => window.__game.scene.getScene('Menu').scene.start('Battle', { levelIndex: 2 }));
await page.waitForTimeout(1500);
const clip = { x: 0, y: 720 - 120, width: 220, height: 120 };
await page.evaluate(() => { const h = window.__game.scene.getScene('Battle').sim.hero; h.xp = 60; });
await page.waitForTimeout(400);
await page.screenshot({ path: `screenshots/${name}-alive.png`, clip });
await page.evaluate(() => { const s = window.__game.scene.getScene('Battle'); const h = s.sim.hero; h.alive = false; h.hp = 0; h.respawnTimer = h.def.respawn * 0.6; s.paused = true; });
await page.waitForTimeout(400);
await page.screenshot({ path: `screenshots/${name}-down.png`, clip });
await page.evaluate(() => { const s = window.__game.scene.getScene('Battle'); const h = s.sim.hero; h.alive = true; h.hp = h.maxHp; s.paused = false; s.handleEvent({ type: 'heroLevel', hero: h }); });
await page.waitForTimeout(150);
await page.evaluate(() => window.__game.scene.getScene('Battle').tweens.pauseAll());
await page.screenshot({ path: `screenshots/${name}-flare.png`, clip: { x: 0, y: 720 - 160, width: 260, height: 160 } });
console.log(errors.length ? 'ERRORS:\n' + errors.join('\n') : 'no console errors');
await browser.close();
server.httpServer.close();
process.exit(errors.length ? 1 : 0);
